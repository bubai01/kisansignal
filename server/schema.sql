CREATE TABLE IF NOT EXISTS users (
  id BIGSERIAL PRIMARY KEY,
  phone TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL DEFAULT '',
  region TEXT NOT NULL DEFAULT '',
  region_idx TEXT NOT NULL DEFAULT '0',
  crop TEXT NOT NULL DEFAULT '0',
  lat DOUBLE PRECISION,
  lon DOUBLE PRECISION,
  lang TEXT NOT NULL DEFAULT 'en',
  alerts INTEGER NOT NULL DEFAULT 1,
  channel TEXT NOT NULL DEFAULT 'sms',
  created BIGINT NOT NULL,
  last_seen BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS otps (
  phone TEXT PRIMARY KEY,
  hash TEXT NOT NULL,
  exp BIGINT NOT NULL,
  tries INTEGER NOT NULL,
  sent BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
  hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  exp BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON sessions(user_id);
CREATE TABLE IF NOT EXISTS fields (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  data JSONB NOT NULL DEFAULT '[]'::jsonb,
  updated BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS alert_log (
  id BIGSERIAL PRIMARY KEY,
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
  region TEXT NOT NULL DEFAULT '',
  level TEXT NOT NULL,
  rain DOUBLE PRECISION NOT NULL,
  channel TEXT NOT NULL,
  status TEXT NOT NULL,
  detail TEXT NOT NULL DEFAULT '',
  ts BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS alert_log_user_ts_idx ON alert_log(user_id, ts);
CREATE TABLE IF NOT EXISTS events (
  id BIGSERIAL PRIMARY KEY,
  type TEXT NOT NULL,
  ts BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS advisor_log (
  id BIGSERIAL PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ts BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS advisor_log_user_ts_idx ON advisor_log(user_id, ts);
